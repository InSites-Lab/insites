// InSites build — assembles the specification from system/modules/ into its
// platform editions. It concatenates and copies text; it adds no runtime logic.
//
//   node system/build/build.mjs              generate the Claude plugin
//   node system/build/build.mjs --check      also verify that the modules, joined
//                                            in manifest order, equal the source
//                                            file named in the manifest
//   node system/build/build.mjs --monolith <out.md>
//                                            write the joined single-file edition
//
// No dependencies. Node 18+.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const MODULES = path.join(ROOT, 'system', 'modules');
const ADAPTER = path.join(HERE, 'claude-plugin');
const PLUGIN_OUT = path.join(ROOT, 'system', 'claude-plugin', 'insites');

const GENERATED =
  '<!-- Generated by system/build/build.mjs from system/modules/. ' +
  'Edit the modules or system/build/claude-plugin/, not this file. -->\n';

const manifest = JSON.parse(fs.readFileSync(path.join(MODULES, 'manifest.json'), 'utf8'));
const byId = new Map(manifest.modules.map((m) => [m.id, m]));

function moduleText(id) {
  const m = byId.get(id);
  if (!m) throw new Error(`Unknown module id: ${id}`);
  return fs.readFileSync(path.join(MODULES, m.file), 'utf8');
}

function joinModules(ids) {
  return ids.map(moduleText).join('');
}

function monolith() {
  return joinModules(manifest.modules.map((m) => m.id));
}

// Split "---\nfrontmatter\n---\n" from the rest of a head file.
function splitFrontmatter(text) {
  const m = text.match(/^---\n[\s\S]*?\n---\n/);
  if (!m) throw new Error('Head file lacks YAML frontmatter');
  return [m[0], text.slice(m[0].length)];
}

function writeFile(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

function buildPlugin() {
  const cfg = JSON.parse(fs.readFileSync(path.join(ADAPTER, 'skills.json'), 'utf8'));
  fs.rmSync(PLUGIN_OUT, { recursive: true, force: true });

  // Static adapter files: plugin manifest, README.
  for (const rel of cfg.static) {
    writeFile(path.join(PLUGIN_OUT, rel), fs.readFileSync(path.join(ADAPTER, rel), 'utf8'));
  }

  // Agents: an authored head plus the modules the agent must apply, so the
  // agent carries its own copy of the rules rather than a path into a skill.
  for (const [file, agent] of Object.entries(cfg.agents || {})) {
    const [front, head] = splitFrontmatter(fs.readFileSync(path.join(ADAPTER, agent.head), 'utf8'));
    writeFile(path.join(PLUGIN_OUT, 'agents', file), front + GENERATED + head + joinModules(agent.body));
  }

  const footers = Object.fromEntries(
    Object.entries(cfg.footers || {}).map(([k, f]) => [k, fs.readFileSync(path.join(ADAPTER, f), 'utf8')])
  );

  for (const [name, skill] of Object.entries(cfg.skills)) {
    const dir = path.join(PLUGIN_OUT, 'skills', name);

    if (skill.copy) {
      // A skill that already exists as a file elsewhere in the repository.
      writeFile(path.join(dir, 'SKILL.md'), fs.readFileSync(path.join(ROOT, skill.copy), 'utf8'));
      continue;
    }

    const [front, head] = splitFrontmatter(fs.readFileSync(path.join(ADAPTER, skill.head), 'utf8'));
    writeFile(path.join(dir, 'SKILL.md'), front + GENERATED + head + joinModules(skill.body));

    for (const [file, ref] of Object.entries(skill.references || {})) {
      const ids = Array.isArray(ref) ? ref : ref.modules;
      const footer = !Array.isArray(ref) && ref.footer ? footers[ref.footer] : '';
      writeFile(path.join(dir, 'references', file), GENERATED + joinModules(ids) + footer);
    }
  }
}

const args = process.argv.slice(2);

buildPlugin();
console.log(`plugin  → ${path.relative(ROOT, PLUGIN_OUT)}`);

if (args.includes('--check')) {
  const src = path.join(ROOT, manifest.source);
  const same = fs.readFileSync(src, 'utf8') === monolith();
  console.log(`check   → modules ${same ? 'equal' : 'DIFFER FROM'} ${manifest.source}`);
  if (!same) process.exitCode = 1;
}

const mi = args.indexOf('--monolith');
if (mi !== -1) {
  const out = args[mi + 1];
  if (!out) throw new Error('--monolith needs an output path');
  writeFile(path.resolve(out), monolith());
  console.log(`monolith → ${out}`);
}
